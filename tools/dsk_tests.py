def read_png(path):
    """Reads back the PNGs written by png() (one IDAT, filter 0, RGB)."""
    d = open(path, 'rb').read()
    w, h = struct.unpack_from('>II', d, 16)
    p, idat = 8, b''
    while p < len(d):
        n = struct.unpack_from('>I', d, p)[0]; t = d[p + 4:p + 8]
        if t == b'IDAT': idat += d[p + 8:p + 8 + n]
        p += 12 + n
    raw = zlib.decompress(idat)
    return w, h, b''.join(raw[y * (w * 3 + 1) + 1:(y + 1) * (w * 3 + 1)] for y in range(h))

def montage(paths, out, cols=3):
    """Contact sheet of snaps (same size), for reviewing a run at a glance."""
    imgs = [read_png(p) for p in paths]
    w, h = max(i[0] for i in imgs), max(i[1] for i in imgs)
    rows = (len(imgs) + cols - 1) // cols
    W, H = w * cols + 4 * (cols - 1), h * rows + 4 * (rows - 1)
    buf = bytearray(b'\x80' * (W * H * 3))
    for i, (iw, ih, px) in enumerate(imgs):
        x0, y0 = (i % cols) * (w + 4), (i // cols) * (h + 4)
        for y in range(ih):
            o = ((y0 + y) * W + x0) * 3
            buf[o:o + iw * 3] = px[y * iw * 3:(y + 1) * iw * 3]
    tmp = out + '.ppm'
    open(tmp, 'wb').write(b'P6\n%d %d\n255\n' % (W, H) + bytes(buf))
    png(tmp, out); os.remove(tmp)

