def bmp2png(bmp, path):
    d = open(bmp, 'rb').read()
    off, w, h, bpp = struct.unpack_from('<I', d, 10)[0], *struct.unpack_from('<iiHH', d, 18)[:2], struct.unpack_from('<H', d, 28)[0]
    stride = (w * bpp // 8 + 3) & ~3
    rows = []
    for y in range(abs(h)):
        r = d[off + y * stride: off + y * stride + w * 3]
        rows.append(bytes(b for i in range(0, len(r), 3) for b in (r[i + 2], r[i + 1], r[i])))
    if h > 0: rows.reverse()
    tmp = path + '.ppm'
    open(tmp, 'wb').write(b'P6\n%d %d\n255\n' % (w, abs(h)) + b''.join(rows))
    png(tmp, path); os.remove(tmp)

def run_cpcec(out, name, steps, end, disk):
    lines, snaps = [], []
    for ln in keyscript(steps, end).splitlines():
        p = ln.split()
        if len(p) < 2 or p[0].startswith('#'): continue
        if p[1] == 'SNAP': snaps.append(int(p[0])); continue
        if p[1] == 'QUIT': continue
        for k in p[1].split('+'):
            lines.append('%s %d %s' % (p[0], MATRIX.index(k), p[2] if len(p) > 2 else '5'))
    kf = os.path.join(out, name + '.cpcec.keys')
    open(kf, 'w').write('\n'.join(lines) + '\n')
