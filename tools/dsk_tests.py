# CPC key positions for each character (Arnold maps the CPC matrix, not a host layout)
SHIFTED = {'"': '2', '!': '1', '#': '3', '$': '4', '%': '5', '&': '6', "'": '7', '(': '8', ')': '9',
           '|': '@', '*': ':', '+': ';', '=': '-', '<': ',', '>': '.', '?': '/'}
PLAIN = {' ': 'SPACE', '\n': 'RETURN', ':': ':', ',': ',', '.': '.', ';': ';', '-': '-', '/': '/', '@': '@'}

def keyname(ch):
    if ch.isalnum(): return ch.upper()
    if ch in PLAIN: return PLAIN[ch]
    if ch in SHIFTED: return 'SHIFT+' + SHIFTED[ch]
    raise ValueError(repr(ch))

def keyscript(steps, end):
    """steps: list of (seconds, text|'SNAP'|'KEY:<name>'). Typing: 3 frames down, 3 up."""
    out = ['# generated by dsk_tests.py']
    for t, what in steps:
        f = int(round(t * 50))
        if what == 'SNAP': out.append('%d SNAP' % f); continue
        if what.startswith('KEY:'): out.append('%d %s 5' % (f, what[4:])); continue
        for ch in what:
            out.append('%d %s 3' % (f, keyname(ch))); f += 6
    out.append('%d QUIT' % int(end * 50))
    return '\n'.join(out) + '\n'

def fdc_results(ram):
    """FDCTEST.BIN records: tests at &5000 (8 bytes), results at &5400 (16 bytes)."""
    out = []
    for i in range(128):
        t = ram[0x5000 + 8 * i:0x5008 + 8 * i]
        if t[0] == 0: break
        r = ram[0x5400 + 16 * i:0x5410 + 16 * i]
        out.append(dict(kind={1: 'id', 2: 'rd', 3: 'fmt'}.get(t[0], '?'), track=t[1], head=t[2], C=t[3], H=t[4], R=t[5], N=t[6],
                        st=tuple(r[0:3]), chrn=tuple(r[3:7]), count=r[7] | r[8] << 8, sum=r[9]))
    return out

def fdc_text(res):
    return '\n'.join('%-2s T%02d h%d %02X: ST %02X %02X %02X  CHRN %02X %02X %02X %02X  count %04X sum %02X' % (
        x['kind'], x['track'], x['head'], x['R'], x['st'][0], x['st'][1], x['st'][2], *x['chrn'], x['count'], x['sum']) for x in res)

def png(ppm, path):
    d = open(ppm, 'rb').read()
    parts = d.split(b'\n', 3)
    w, h = map(int, parts[1].split()); px = parts[3]
    raw = b''.join(b'\0' + px[y * w * 3:(y + 1) * w * 3] for y in range(h))
    def chunk(t, b): return struct.pack('>I', len(b)) + t + b + struct.pack('>I', zlib.crc32(t + b) & 0xffffffff)
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
                           + chunk(b'IDAT', zlib.compress(raw, 6)) + chunk(b'IEND', b''))

def run(hd, out, name, steps, end, diska=None, diskb=None, diskout=None, diskoutb=None, cart=CART):
    ks = os.path.join(out, name + '.keys')
    open(ks, 'w').write(keyscript(steps, end))
    env = dict(os.environ)
    base = os.path.join(out, name)
    for k, v in (('DISKA', diska), ('DISKB', diskb), ('DISKOUT', diskout), ('DISKOUTB', diskoutb), ('RAMOUT', base + '.ram')):
        env.pop(k, None)
        if v: env[k] = v
    base = os.path.join(out, name)
    p = subprocess.run([hd, str(int(end * 50) + 10), base + '.ppm', cart, '8', ks], env=env,
                       capture_output=True, text=True, timeout=900)
    log = p.stdout + p.stderr
    open(base + '.log', 'w').write(log)
    snaps = []
    for m in re.finditer(r'snap frame=(\d+)', p.stdout):
        if True:
            fr = int(m.group(1))
            ppm = '%s.ppm.%d.ppm' % (base, fr)
            pngp = '%s_%04d.png' % (base, fr)
            png(ppm, pngp); os.remove(ppm); snaps.append(pngp)
    if os.path.exists(base + '.ppm'): os.remove(base + '.ppm')
    print('== %s (exit %d)' % (name, p.returncode)); print(log.strip())
    return p.returncode, log, snaps

# ------------------------------------------------------------ AMSDOS read --
def read_image(path):
    """Parse a DSK/EDSK into {(track, side): [(C,H,R,N,ST1,ST2,data)]}."""
    d = open(path, 'rb').read()
    ext = d[:8] == b'EXTENDED'
    nt, ns = d[0x30], d[0x31]
    tracks, off = {}, 256
    for i in range(nt * ns):
        size = d[0x34 + i] << 8 if ext else struct.unpack_from('<H', d, 0x32)[0]
        if size == 0: tracks[(i // ns, i % ns)] = []; continue
        th = d[off:off + 512]; assert th[:10] == b'Track-Info', (path, i)
        spt = th[0x15]; p = off + (512 if ext and spt > 29 else 256); secs = []
        spt = min(spt, 61 if ext else 29)
        for s in range(spt):
            C, H, R, N, s1, s2, l = struct.unpack_from('<BBBBBBH', th, 0x18 + 8 * s)
            if not ext: l = 128 << (th[0x14] & 7)       # standard: every sector is the track's size
            elif l == 0: l = 128 << (N & 7)               # old extended images: no stored length
            secs.append((C, H, R, N, s1, s2, d[p:min(p + l, off + size)])); p += l
        tracks[(i // ns, i % ns)] = secs; off += size
    return tracks

def fnv(b):
    h = 2166136261
    for x in b: h = ((h ^ x) * 16777619) & 0xffffffff
    return h

def expected_dump(path):
    """What the core should hold: each sector's stored data cut or padded (with the
    track's filler byte) to 128<<N, as the FDC reads it."""
    d = open(path, 'rb').read()
    ext = d[:8] == b'EXTENDED'; ns = d[0x31]
    lines, off = [], 256
    tracks = read_image(path)
    for i in range(d[0x30] * ns):
        size = d[0x34 + i] << 8 if ext else struct.unpack_from('<H', d, 0x32)[0]
        t, s = i // ns, i % ns
        if size:
            filler = d[off + 0x17]
            for k, (C, H, R, N, s1, s2, data) in enumerate(tracks[(t, s)]):
                n = 128 << (N & 7)
                lines.append('%d %d %d %02X %02X %02X %02X %02X %02X %08X' % (t, s, k, C, H, R, N, s1, s2,
                             fnv(data[:n].ljust(n, bytes([filler])))))
        off += size
    return lines

def dump_check(hd, out, name, image):
    """Load the image in the core (no emulation) and compare every sector."""
    dump = os.path.join(out, name + '.secdump')
    env = dict(os.environ, DISKA=image, DISKDUMP=dump)
    subprocess.run([hd, '1', os.path.join(out, 'x.ppm'), CART, '8'], env=env, capture_output=True, timeout=60)
    os.remove(os.path.join(out, 'x.ppm'))
    got = open(dump).read().split('\n')[:-1]
    want = expected_dump(image)
    bad = [(w, g) for w, g in zip(want, got) if w != g]
    ok = len(got) == len(want) and not bad
    print('  sector dump %-18s %s (%d sectors%s)' % (os.path.basename(image), 'PASS' if ok else 'FAIL', len(want),
          '' if ok else ', %d differ, %d vs %d lines; first: want %s got %s' % (len(bad), len(want), len(got), *(bad[0] if bad else ('-', '-')))))
    return ('secdump_' + name, 0 if ok else 1, '', [])

def amsdos_dir(path):
    tr = read_image(path)
    def sector(t, r):
        for s in tr.get((t, 0), []):
            if s[2] == r: return s[6]
        return None
    base, res = (0x41, 2) if sector(0, 0x41) is not None and sector(0, 0xC1) is None else (0xC1, 0)
    def block(b):
        return b''.join(sector(res + (2 * b + i) // 9, base + (2 * b + i) % 9) or b'' for i in range(2))
    d = block(0) + block(1)
    files = {}
    for e in range(64):
        ent = d[e * 32:(e + 1) * 32]
        if len(ent) < 32 or ent[0] == 0xE5: continue
        name = (ent[1:9].decode('latin-1').rstrip() + '.' + bytes(c & 0x7f for c in ent[9:12]).decode().rstrip())
        files.setdefault(name, []).append((ent[12], ent[15], [b for b in ent[16:32] if b]))
    out = {}
    for name, exts in files.items():
        exts.sort(); data = b''; recs = 0
        for ex, rc, al in exts:
            data += b''.join(block(b) for b in al); recs += rc
        out[name] = data[:recs * 128]
    return out

def header_ok(data):
    return len(data) >= 128 and struct.unpack_from('<H', data, 67)[0] == sum(data[:67]) & 0xffff

def fdc_check(name, ramfile, image):
    """Compare FDCTEST READ DATA results with the image itself."""
    res = fdc_results(open(ramfile, 'rb').read())
    tr = read_image(image)
    print('  FDC results (%s):' % name); print('  ' + fdc_text(res).replace('\n', '\n  '))
    bad = 0
    for x in res:
        if x['kind'] != 'rd': continue
        secs = tr.get((x['track'], x['head']), [])
        hit = [q for q in secs if q[:4] == (x['C'], x['H'], x['R'], x['N'])]
        if hit:
            d = hit[0][6][:128 << x['N']]
            if x['N'] == 0:
                d = d[:0x50]          # Arnold: N=0 transfers &50 bytes ("tested on CPC+ fdc", fdc.c)
            ok = x['count'] == len(d) and x['sum'] == sum(d) & 255 and \
                 ((x['st'][0] & 0xC0) == 0x40 or (hit[0][5] & 0x40 and x['st'][2] & 0x40))   # deleted mark: CM set
            why = 'want count %04X sum %02X' % (len(d), sum(d) & 255)
        else:
            ok = (x['st'][0] & 0xC0) == 0x40 and (x['st'][1] & 0x05) != 0 and x['count'] == 0
            why = 'want not found (ST0 4x, ST1 ND/MA)'
        bad += not ok
        print('  %s T%02d h%d R%02X: %s' % ('ok  ' if ok else 'FAIL', x['track'], x['head'], x['R'], why))
    return (name + '_check', 1 if bad else 0, '', [])

